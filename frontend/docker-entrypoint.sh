#!/bin/sh
# docker-entrypoint.sh — called when the frontend container starts.
#
# Waits for the hardhat-deploy service to finish deploying the contract,
# then injects the contract address into the Vite environment before
# starting the dev server.

set -e

DEPLOYMENT_FILE="/shared/deployment.json"
ENV_FILE="/app/.env"

# ------------------------------------------------------------------
# 1. Wait for the deployment file (written by hardhat-deploy).
# ------------------------------------------------------------------
echo "[frontend] Waiting for contract deployment..."
WAIT=0
until [ -f "$DEPLOYMENT_FILE" ]; do
  sleep 2
  WAIT=$((WAIT + 2))
  if [ $WAIT -ge 120 ]; then
    echo "[frontend] Timed out waiting for deployment. Starting without contract address."
    break
  fi
done

# ------------------------------------------------------------------
# 2. Inject the contract address into .env so Vite can read it.
# ------------------------------------------------------------------
if [ -f "$DEPLOYMENT_FILE" ]; then
  # Use node (already available) to parse the JSON safely.
  CONTRACT_ADDRESS=$(node -e "
    const d = require('$DEPLOYMENT_FILE');
    process.stdout.write(d.contractAddress || '');
  ")
  echo "[frontend] Contract address: $CONTRACT_ADDRESS"

  # Write (or overwrite) the .env file.
  # VITE_API_URL points to the backend container (service name = 'backend').
  # The user's browser talks to localhost:8000 — this is the CORS origin
  # that the backend allows, not the internal container address.
  cat > "$ENV_FILE" <<EOF
# Auto-generated by docker-entrypoint.sh — do not edit manually.
VITE_CONTRACT_ADDRESS=${CONTRACT_ADDRESS}
VITE_API_URL=${VITE_API_URL:-http://localhost:8000}
EOF
  echo "[frontend] .env written."
else
  echo "[frontend] No deployment file found; VITE_CONTRACT_ADDRESS will be empty."
fi

# ------------------------------------------------------------------
# 3. Start the Vite dev server, binding to all interfaces.
# ------------------------------------------------------------------
echo "[frontend] Starting Vite dev server..."
exec npm run dev -- --host 0.0.0.0
